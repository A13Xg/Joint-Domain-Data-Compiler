import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

// Generates THIRD_PARTY_NOTICES.md: the copyright and license notices of every
// package compiled into the app, which their licenses (MIT, BSD) require to
// travel with every copy. The production bundle strips the comments that
// would otherwise carry them, so this file ships instead -- in the web build
// (vite.config.ts) and beside the desktop executable (package.json
// build.*.extraFiles).
//
// It is also the guard that keeps the project's AGPL-3.0 honest. react-leaflet
// once arrived under the Hippocratic License, whose use restrictions cannot be
// combined with the AGPL (section 10), and nothing noticed. Every runtime
// dependency's license must now be on ALLOWED_LICENSES, or this fails.
//
// Usage: node scripts/third-party-notices.mjs          write the file
//        node scripts/third-party-notices.mjs --check  fail if it is stale

export const NOTICES_FILE = 'THIRD_PARTY_NOTICES.md'

// Permissive licenses that can be combined into an AGPL-3.0 program. Anything
// else -- copyleft with other terms, "ethical source", non-commercial,
// proprietary -- needs a human decision before it ships.
export const ALLOWED_LICENSES = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'Zlib', 'CC0-1.0', 'Unlicense', 'BlueOak-1.0.0'])

/** Every package in the production dependency tree, deduplicated, sorted. */
export function collectRuntimePackages(root = '.') {
  const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, shell: process.platform === 'win32' }))
  const found = new Map()
  const walk = (dependencies) => {
    for (const [name, node] of Object.entries(dependencies ?? {})) {
      if (!found.has(name)) {
        const dir = join(root, 'node_modules', name)
        const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
        const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN')
        const licenseFile = readdirSync(dir).find((file) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(file))
        found.set(name, {
          name,
          version: pkg.version,
          license,
          homepage: pkg.homepage ?? (typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url) ?? '',
          // LF only: some packages ship CRLF license files, which git normalises
          // on checkout, so CI would see a file that no longer matched.
          licenseText: licenseFile ? readFileSync(join(dir, licenseFile), 'utf8').replace(/\r\n?/g, '\n').trim() : null,
        })
      }
      walk(node.dependencies)
    }
  }
  walk(tree.dependencies)
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name))
}

/** Licenses outside the allowlist, or packages shipped without a license text. */
export function licenseProblems(packages) {
  const problems = []
  for (const pkg of packages) {
    const licenses = pkg.license.replace(/[()]/g, '').split(/\s+OR\s+/)
    // "A OR B" is fine when either option is allowed; "A AND B" needs both.
    const allowed = licenses.some((option) => option.split(/\s+AND\s+/).every((part) => ALLOWED_LICENSES.has(part.trim())))
    if (!allowed) problems.push(`${pkg.name}@${pkg.version} is licensed "${pkg.license}", which is not on the AGPL-compatible allowlist in scripts/third-party-notices.mjs.`)
    if (!pkg.licenseText) problems.push(`${pkg.name}@${pkg.version} ships no LICENSE file, so its notice cannot be reproduced.`)
  }
  return problems
}

export function renderNotices(packages) {
  const lines = [
    '# Third-party notices',
    '',
    'Joint Domain Data Compiler is licensed under the GNU Affero General Public License v3.0 (see',
    '`LICENSE`). It includes the following third-party software, whose licenses require these',
    'notices to accompany every copy.',
    '',
    '<!-- Generated by `node scripts/third-party-notices.mjs` from the production dependency tree.',
    '     Do not edit by hand; test/third-party-notices.ts fails when it is out of date. -->',
    '',
    '## Software compiled into the application',
    '',
    '| Package | Version | License |',
    '|---|---|---|',
    ...packages.map((pkg) => `| ${pkg.name} | ${pkg.version} | ${pkg.license} |`),
    '',
    '## Other components',
    '',
    '- **Electron** (MIT) and **Chromium** (BSD-3-Clause and others) form the desktop runtime. Their',
    '  notices ship beside the desktop executable as `LICENSE.electron.txt` and',
    '  `LICENSES.chromium.html`.',
    '- **Special Use Airspace overlay** (`Special_Use_Airspace.kml`): U.S. Federal Aviation',
    '  Administration special use airspace data. Works of the U.S. Government are not subject to',
    '  copyright in the United States.',
    '- **Map tiles** are not distributed with the application. When a network basemap is selected they',
    '  are fetched from OpenStreetMap, CARTO or OpenTopoMap, and the map displays each provider\'s',
    '  required attribution.',
    '',
    '## License texts',
    '',
  ]
  for (const pkg of packages) {
    lines.push(`### ${pkg.name} ${pkg.version}`, '')
    if (pkg.homepage) lines.push(pkg.homepage.replace(/^git\+/, ''), '')
    lines.push('```', pkg.licenseText ?? `(${pkg.license}; no license file in the package)`, '```', '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

if (process.argv[1] && basename(process.argv[1]) === 'third-party-notices.mjs') {
  const packages = collectRuntimePackages()
  const problems = licenseProblems(packages)
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem)
    process.exit(1)
  }
  const text = renderNotices(packages)
  if (process.argv.includes('--check')) {
    const current = existsSync(NOTICES_FILE) ? readFileSync(NOTICES_FILE, 'utf8') : ''
    if (current !== text) {
      console.error(`${NOTICES_FILE} is out of date; run: node scripts/third-party-notices.mjs`)
      process.exit(1)
    }
    console.log(`${NOTICES_FILE} is current (${packages.length} packages, all AGPL-compatible).`)
  } else {
    writeFileSync(NOTICES_FILE, text)
    console.log(`Wrote ${NOTICES_FILE} (${packages.length} packages, all AGPL-compatible).`)
  }
}
